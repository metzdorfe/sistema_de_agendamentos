CREATE TABLE CLIENTE (
    ID              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOME            VARCHAR(100) NOT NULL,
    CPF_CNPJ        VARCHAR(14),
    TELEFONE        VARCHAR(11) NOT NULL,
    EMAIL           VARCHAR(100),
    LOGRADOURO      VARCHAR(100),
    NUMERO          VARCHAR(10),
    COMPLEMENTO     VARCHAR(60),
    BAIRRO          VARCHAR(60),
    CIDADE          VARCHAR(60),
    UF              D_UF,
    CEP             CHAR(8),
    DATA_CADASTRO   DATE DEFAULT CURRENT_DATE NOT NULL,
    ATIVO           D_ATIVO,
    ACEITA_WHATSAPP BOOLEAN DEFAULT TRUE NOT NULL
);
COMMENT ON TABLE CLIENTE IS 'Quem contrata o evento, pessoa física ou jurídica.';
COMMENT ON COLUMN CLIENTE.ACEITA_WHATSAPP IS 'Consentimento para receber mensagens pelo WhatsApp (LGPD). Desmarcado, o sistema não envia.';
COMMENT ON COLUMN CLIENTE.CPF_CNPJ IS 'Opcional; só dígitos (11 = CPF, 14 = CNPJ); se preenchido, único e válido (RN01).';
COMMENT ON COLUMN CLIENTE.TELEFONE IS 'Obrigatório; só dígitos, com DDD (10 ou 11). A máscara é só da tela.';
COMMENT ON COLUMN CLIENTE.EMAIL IS 'Opcional.';
COMMENT ON COLUMN CLIENTE.LOGRADOURO IS 'Endereço opcional: rua/avenida.';
COMMENT ON COLUMN CLIENTE.CEP IS 'Só dígitos (8).';
COMMENT ON COLUMN CLIENTE.ATIVO IS 'Cliente com agendamento não é excluído, é inativado (RN02).';

CREATE UNIQUE INDEX UX_CLIENTE_CPF_CNPJ ON CLIENTE (CPF_CNPJ);
CREATE INDEX IX_CLIENTE_NOME ON CLIENTE (NOME);

ALTER TABLE CLIENTE ADD CONSTRAINT CK_CLIENTE_CPF_CNPJ
  CHECK (CPF_CNPJ IS NULL OR CHAR_LENGTH(CPF_CNPJ) IN (11, 14));

CREATE TABLE SERVICO (
    ID              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOME            VARCHAR(80) NOT NULL,
    DESCRICAO       VARCHAR(255),
