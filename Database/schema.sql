CREATE DOMAIN D_VALOR              AS NUMERIC(18,2) DEFAULT 0 NOT NULL;
CREATE DOMAIN D_PERCENTUAL         AS NUMERIC(5,2)  DEFAULT 0 NOT NULL;
CREATE DOMAIN D_ATIVO              AS BOOLEAN DEFAULT TRUE NOT NULL;
CREATE DOMAIN D_STATUS_AGENDAMENTO AS CHAR(1) NOT NULL CHECK (VALUE IN ('O','A','F','C'));
CREATE DOMAIN D_STATUS_RECEBER     AS CHAR(1) NOT NULL CHECK (VALUE IN ('A','P','C'));
CREATE DOMAIN D_TIPO_LANCAMENTO    AS CHAR(1) NOT NULL CHECK (VALUE IN ('E','S'));
CREATE DOMAIN D_TEMA               AS CHAR(1) DEFAULT 'C' NOT NULL CHECK (VALUE IN ('E','C','S'));
CREATE DOMAIN D_UF                 AS CHAR(2);
CREATE DOMAIN D_CAMINHO_ARQUIVO    AS VARCHAR(260);

COMMENT ON DOMAIN D_VALOR IS 'Valor monetário em reais.';
COMMENT ON DOMAIN D_PERCENTUAL IS 'Percentual (ex.: 2.00 = 2%).';
COMMENT ON DOMAIN D_ATIVO IS 'Exclusão lógica: FALSE = inativado, não aparece para novo uso.';
COMMENT ON DOMAIN D_STATUS_AGENDAMENTO IS 'O=Orçamento, A=Agendado, F=Faturado, C=Cancelado.';
COMMENT ON DOMAIN D_STATUS_RECEBER IS 'A=Aberto, P=Pago, C=Cancelado.';
COMMENT ON DOMAIN D_TIPO_LANCAMENTO IS 'E=Entrada, S=Saída.';
COMMENT ON DOMAIN D_TEMA IS 'E=Escuro, C=Claro (padrão), S=Seguir o Windows.';
COMMENT ON DOMAIN D_UF IS 'Sigla do estado (ex.: SC).';
COMMENT ON DOMAIN D_CAMINHO_ARQUIVO IS 'Caminho de arquivo relativo à pasta Arquivos\ do sistema (ex.: Empresa\logo.png). O arquivo fica fora do banco.';

