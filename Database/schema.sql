CREATE TABLE CLIENTE (
    ID              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOME            VARCHAR(100) NOT NULL,
    CPF_CNPJ        VARCHAR(14),
    TELEFONE        VARCHAR(11) NOT NULL,
    EMAIL           VARCHAR(100),
    LOGRADOURO      VARCHAR(100),
    NUMERO          VARCHAR(10),
    COMPLEMENTO     VARCHAR(60),
    BAIRRO          VARCHAR(60),
    CIDADE          VARCHAR(60),
    UF              D_UF,
    CEP             CHAR(8),
    DATA_CADASTRO   DATE DEFAULT CURRENT_DATE NOT NULL,
    ATIVO           D_ATIVO
);
COMMENT ON TABLE CLIENTE IS 'Quem contrata o evento, pessoa física ou jurídica.';
COMMENT ON COLUMN CLIENTE.CPF_CNPJ IS 'Opcional; só dígitos (11 = CPF, 14 = CNPJ); se preenchido, único e válido (RN01).';
COMMENT ON COLUMN CLIENTE.TELEFONE IS 'Obrigatório; só dígitos, com DDD (10 ou 11). A máscara é só da tela.';
COMMENT ON COLUMN CLIENTE.EMAIL IS 'Opcional.';
COMMENT ON COLUMN CLIENTE.LOGRADOURO IS 'Endereço opcional: rua/avenida.';
COMMENT ON COLUMN CLIENTE.CEP IS 'Só dígitos (8).';
COMMENT ON COLUMN CLIENTE.ATIVO IS 'Cliente com agendamento não é excluído, é inativado (RN02).';

CREATE UNIQUE INDEX UX_CLIENTE_CPF_CNPJ ON CLIENTE (CPF_CNPJ);
CREATE INDEX IX_CLIENTE_NOME ON CLIENTE (NOME);

ALTER TABLE CLIENTE ADD CONSTRAINT CK_CLIENTE_CPF_CNPJ
  CHECK (CPF_CNPJ IS NULL OR CHAR_LENGTH(CPF_CNPJ) IN (11, 14));

CREATE TABLE SERVICO (
    ID              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOME            VARCHAR(80) NOT NULL,
    DESCRICAO       VARCHAR(255),
    ATIVO           D_ATIVO
);
COMMENT ON TABLE SERVICO IS 'Serviço principal (o espaço). Não guarda preço — ver SERVICO_FAIXA.';
COMMENT ON COLUMN SERVICO.ATIVO IS 'Serviço usado não é excluído, é inativado (RN02).';

CREATE TABLE SERVICO_FAIXA (
    ID              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    SERVICO_ID      INTEGER NOT NULL,
    NOME            VARCHAR(80) NOT NULL,
    VALOR           D_VALOR,
    ORDEM_EXIBICAO  SMALLINT DEFAULT 0 NOT NULL,
    ATIVO           D_ATIVO,
    CONSTRAINT FK_SERVICO_FAIXA_SERVICO FOREIGN KEY (SERVICO_ID) REFERENCES SERVICO (ID)
);
COMMENT ON TABLE SERVICO_FAIXA IS 'Faixas de preço de cada serviço (ex.: Seg a Qua, Fim de semana/Feriado, Promoção).';
COMMENT ON COLUMN SERVICO_FAIXA.ORDEM_EXIBICAO IS 'Ordem de exibição na tela e no catálogo (arrastar e soltar).';
COMMENT ON COLUMN SERVICO_FAIXA.ATIVO IS 'Faixa usada em agendamento não é excluída, é inativada (RN02, RN03).';

CREATE INDEX IX_SERVICO_FAIXA_SERVICO ON SERVICO_FAIXA (SERVICO_ID);

CREATE TABLE ADICIONAL (
    ID                      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOME                    VARCHAR(80) NOT NULL,
    DESCRICAO               VARCHAR(255),
    VALOR_VENDA             D_VALOR,
    VALOR_CUSTO             D_VALOR,
    COBRA_POR_QUANTIDADE    BOOLEAN DEFAULT FALSE NOT NULL,
    ATIVO                   D_ATIVO
);
COMMENT ON TABLE ADICIONAL IS 'Garçom, comida, decoração, etc. Cadastrado pela tela do serviço.';
COMMENT ON COLUMN ADICIONAL.VALOR_VENDA IS 'O que se cobra do cliente.';
COMMENT ON COLUMN ADICIONAL.VALOR_CUSTO IS 'O que a empresa paga (ex.: o garçom).';
COMMENT ON COLUMN ADICIONAL.COBRA_POR_QUANTIDADE IS 'Se verdadeiro, total = quantidade × valor (RN04).';

CREATE TABLE SERVICO_ADICIONAL (
    SERVICO_ID      INTEGER NOT NULL,
    ADICIONAL_ID    INTEGER NOT NULL,
    CONSTRAINT PK_SERVICO_ADICIONAL PRIMARY KEY (SERVICO_ID, ADICIONAL_ID),
    CONSTRAINT FK_SERVICO_ADICIONAL_SERVICO FOREIGN KEY (SERVICO_ID) REFERENCES SERVICO (ID),
    CONSTRAINT FK_SERVICO_ADICIONAL_ADICIONAL FOREIGN KEY (ADICIONAL_ID) REFERENCES ADICIONAL (ID)
);
COMMENT ON TABLE SERVICO_ADICIONAL IS 'Quais adicionais cada serviço oferece (N:N pura, RN07).';

CREATE TABLE ESPECIE (
    ID                      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    DESCRICAO               VARCHAR(80) NOT NULL,
    PERMITE_PARCELAMENTO    BOOLEAN DEFAULT FALSE NOT NULL,
    ATIVO                   D_ATIVO
);
COMMENT ON TABLE ESPECIE IS 'Formas de pagamento (dinheiro, pix, cartão...).';
COMMENT ON COLUMN ESPECIE.PERMITE_PARCELAMENTO IS 'Se essa espécie aceita mais de 1 parcela (RN15).';
COMMENT ON COLUMN ESPECIE.ATIVO IS 'Espécie usada não é excluída, é inativada (RN02).';

