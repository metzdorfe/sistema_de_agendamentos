CREATE TABLE AGENDAMENTO (
    ID                      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CLIENTE_ID              INTEGER NOT NULL,
    TITULO                  VARCHAR(80) NOT NULL,
    DATA_EVENTO             DATE NOT NULL,
    HORA_INICIO             TIME NOT NULL,
    HORA_FIM                TIME NOT NULL,
    QUANTIDADE_CONVIDADOS   SMALLINT,
    STATUS                  D_STATUS_AGENDAMENTO,
    VALOR_DESCONTO          D_VALOR,
    VALOR_TOTAL             D_VALOR,
    DATA_CANCELAMENTO       DATE,
    MOTIVO_CANCELAMENTO     VARCHAR(200),
    OBSERVACAO              VARCHAR(500),
    DATA_CADASTRO           DATE DEFAULT CURRENT_DATE NOT NULL,
    CONSTRAINT FK_AGENDAMENTO_CLIENTE FOREIGN KEY (CLIENTE_ID) REFERENCES CLIENTE (ID)
);
COMMENT ON TABLE AGENDAMENTO IS 'O evento.';
COMMENT ON COLUMN AGENDAMENTO.TITULO IS 'Nome curto do evento (ex.: Festa Infantil), mostrado no calendário e na agenda do dia.';
COMMENT ON COLUMN AGENDAMENTO.HORA_INICIO IS 'Início do evento. O evento pertence sempre à DATA_EVENTO (RN28).';
COMMENT ON COLUMN AGENDAMENTO.HORA_FIM IS 'Fim do evento. Menor que HORA_INICIO = termina no dia seguinte (RN28).';
COMMENT ON COLUMN AGENDAMENTO.STATUS IS 'O=Orçamento, A=Agendado, F=Faturado, C=Cancelado.';
COMMENT ON COLUMN AGENDAMENTO.VALOR_TOTAL IS 'Soma dos serviços + adicionais - desconto. Desnormalização consciente (RN09).';
COMMENT ON COLUMN AGENDAMENTO.VALOR_DESCONTO IS 'Manual, só pode ser informado até o faturamento (RN13).';
COMMENT ON COLUMN AGENDAMENTO.DATA_CANCELAMENTO IS 'Obrigatória ao cancelar, vazia nos demais casos (RN22, RN27).';
COMMENT ON COLUMN AGENDAMENTO.MOTIVO_CANCELAMENTO IS 'Obrigatório ao cancelar (RN22).';

CREATE INDEX IX_AGENDAMENTO_DATA_EVENTO ON AGENDAMENTO (DATA_EVENTO);
CREATE INDEX IX_AGENDAMENTO_CLIENTE ON AGENDAMENTO (CLIENTE_ID);

ALTER TABLE AGENDAMENTO ADD CONSTRAINT CK_AGENDAMENTO_CANCELAMENTO
  CHECK ((STATUS = 'C' AND DATA_CANCELAMENTO IS NOT NULL AND MOTIVO_CANCELAMENTO IS NOT NULL)
      OR (STATUS <> 'C' AND DATA_CANCELAMENTO IS NULL AND MOTIVO_CANCELAMENTO IS NULL));

ALTER TABLE AGENDAMENTO ADD CONSTRAINT CK_AGENDAMENTO_DATA_CANCELAMENTO
  CHECK (DATA_CANCELAMENTO IS NULL OR DATA_CANCELAMENTO <= DATA_EVENTO);

CREATE TABLE SERVICO_AGENDAMENTO (
    ID                  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    AGENDAMENTO_ID      INTEGER NOT NULL,
    SERVICO_ID          INTEGER NOT NULL,
    SERVICO_FAIXA_ID    INTEGER NOT NULL,
    VALOR_UNITARIO      D_VALOR,
    CONSTRAINT FK_SERVICO_AGENDAMENTO_AGENDAMENTO FOREIGN KEY (AGENDAMENTO_ID) REFERENCES AGENDAMENTO (ID),
    CONSTRAINT FK_SERVICO_AGENDAMENTO_SERVICO FOREIGN KEY (SERVICO_ID) REFERENCES SERVICO (ID),
    CONSTRAINT FK_SERVICO_AGENDAMENTO_FAIXA FOREIGN KEY (SERVICO_FAIXA_ID) REFERENCES SERVICO_FAIXA (ID)
);
COMMENT ON TABLE SERVICO_AGENDAMENTO IS 'Serviços principais de cada agendamento (RN05).';
COMMENT ON COLUMN SERVICO_AGENDAMENTO.SERVICO_FAIXA_ID IS 'Faixa escolhida; o valor é copiado, não recalculado (RN06, RN08).';
COMMENT ON COLUMN SERVICO_AGENDAMENTO.VALOR_UNITARIO IS 'Vem da faixa escolhida e pode ser alterado (RN06, RN08).';

CREATE INDEX IX_SERVICO_AGENDAMENTO_AGENDAMENTO ON SERVICO_AGENDAMENTO (AGENDAMENTO_ID);

CREATE TABLE ADICIONAL_AGENDAMENTO (
    ID                          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    AGENDAMENTO_ID              INTEGER NOT NULL,
    ADICIONAL_ID                INTEGER NOT NULL,
    QUANTIDADE                  SMALLINT DEFAULT 1 NOT NULL,
    VALOR_UNITARIO              D_VALOR,
    VALOR_CUSTO_UNITARIO        D_VALOR,
    CONSTRAINT FK_ADICIONAL_AGENDAMENTO_AGENDAMENTO FOREIGN KEY (AGENDAMENTO_ID) REFERENCES AGENDAMENTO (ID),
    CONSTRAINT FK_ADICIONAL_AGENDAMENTO_ADICIONAL FOREIGN KEY (ADICIONAL_ID) REFERENCES ADICIONAL (ID)
);
COMMENT ON TABLE ADICIONAL_AGENDAMENTO IS 'Adicionais contratados em cada agendamento (RN07).';
COMMENT ON COLUMN ADICIONAL_AGENDAMENTO.QUANTIDADE IS 'RN04: só varia quando o adicional cobra por quantidade; senão fica 1.';
COMMENT ON COLUMN ADICIONAL_AGENDAMENTO.VALOR_UNITARIO IS 'Copiado do cadastro no momento do agendamento (RN08).';
COMMENT ON COLUMN ADICIONAL_AGENDAMENTO.VALOR_CUSTO_UNITARIO IS 'Copiado do cadastro no momento do agendamento (RN08); usado para o lucro do evento (RF16).';

CREATE INDEX IX_ADICIONAL_AGENDAMENTO_AGENDAMENTO ON ADICIONAL_AGENDAMENTO (AGENDAMENTO_ID);

