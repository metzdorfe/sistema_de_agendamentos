-- ---------------------------------------------------------------------------
-- Domínios novos
-- ---------------------------------------------------------------------------
CREATE DOMAIN D_TEMA   AS CHAR(1) DEFAULT 'E' NOT NULL CHECK (VALUE IN ('E','C','S'));
CREATE DOMAIN D_UF     AS CHAR(2);
CREATE DOMAIN D_IMAGEM AS BLOB SUB_TYPE BINARY;

COMMENT ON DOMAIN D_TEMA IS 'E=Escuro, C=Claro, S=Seguir o Windows.';
COMMENT ON DOMAIN D_UF IS 'Sigla do estado (ex.: SC).';
COMMENT ON DOMAIN D_IMAGEM IS 'Imagem gravada no próprio banco (ex.: logo da empresa).';

COMMIT;

-- ---------------------------------------------------------------------------
-- FINANCEIRO e RECEBER: recriadas (ID do RECEBER passa a INTEGER, TIPO_LANCAMENTO vira TIPO)
-- ---------------------------------------------------------------------------
DROP TABLE FINANCEIRO;
DROP TABLE RECEBER;

COMMIT;

CREATE TABLE RECEBER (
    ID                  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    AGENDAMENTO_ID      INTEGER NOT NULL,
    ESPECIE_ID          INTEGER NOT NULL,
    PARCELA_ORIGEM_ID   INTEGER,
    NUMERO_PARCELA      SMALLINT DEFAULT 1 NOT NULL,
    VALOR_PARCELA       D_VALOR,
    DATA_VENCIMENTO     DATE NOT NULL,
    VALOR_JUROS         D_VALOR,
    VALOR_MULTA         D_VALOR,
    VALOR_RECEBIDO      D_VALOR,
    DATA_RECEBIMENTO    DATE,
    STATUS              D_STATUS_RECEBER,
    CONSTRAINT FK_RECEBER_AGENDAMENTO FOREIGN KEY (AGENDAMENTO_ID) REFERENCES AGENDAMENTO (ID),
    CONSTRAINT FK_RECEBER_ESPECIE FOREIGN KEY (ESPECIE_ID) REFERENCES ESPECIE (ID),
    CONSTRAINT FK_RECEBER_ORIGEM FOREIGN KEY (PARCELA_ORIGEM_ID) REFERENCES RECEBER (ID)
);
COMMENT ON TABLE RECEBER IS 'Parcelas ainda não pagas, com vencimento no futuro. Só existe quando há algo pendente (RN12, RN16).';
COMMENT ON COLUMN RECEBER.ESPECIE_ID IS 'Espécie combinada; a real (usada na baixa) pode ser diferente (RN20).';
COMMENT ON COLUMN RECEBER.STATUS IS 'A=Aberto, P=Pago, C=Cancelado.';
COMMENT ON COLUMN RECEBER.VALOR_JUROS IS 'Preenchido na baixa: juros por dia de atraso (RN18).';
COMMENT ON COLUMN RECEBER.VALOR_MULTA IS 'Preenchido na baixa: multa sobre a parcela (RN18).';
COMMENT ON COLUMN RECEBER.VALOR_RECEBIDO IS 'Total que entrou (parcela + multa + juros, ou menos, se baixa parcial).';
COMMENT ON COLUMN RECEBER.PARCELA_ORIGEM_ID IS 'Preenchido só na parcela criada para cobrar a diferença de uma baixa parcial (RN19).';

CREATE INDEX IX_RECEBER_STATUS_VENCIMENTO ON RECEBER (STATUS, DATA_VENCIMENTO);
CREATE INDEX IX_RECEBER_AGENDAMENTO ON RECEBER (AGENDAMENTO_ID);

CREATE TABLE FINANCEIRO (
    ID                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    DATA_LANCAMENTO     DATE NOT NULL,
    TIPO                D_TIPO_LANCAMENTO,
    VALOR               D_VALOR,
    ESPECIE_ID          INTEGER NOT NULL,
    RECEBER_ID          INTEGER,
    AGENDAMENTO_ID      INTEGER,
    DESCRICAO           VARCHAR(200),
    CONSTRAINT FK_FINANCEIRO_RECEBER FOREIGN KEY (RECEBER_ID) REFERENCES RECEBER (ID),
    CONSTRAINT FK_FINANCEIRO_AGENDAMENTO FOREIGN KEY (AGENDAMENTO_ID) REFERENCES AGENDAMENTO (ID),
    CONSTRAINT FK_FINANCEIRO_ESPECIE FOREIGN KEY (ESPECIE_ID) REFERENCES ESPECIE (ID)
);
COMMENT ON TABLE FINANCEIRO IS 'O que entrou ou saiu de fato ("caixa"). No máximo uma de RECEBER_ID/AGENDAMENTO_ID preenchida.';
COMMENT ON COLUMN FINANCEIRO.TIPO IS 'E=Entrada, S=Saída.';
COMMENT ON COLUMN FINANCEIRO.RECEBER_ID IS 'Preenchido em baixa de parcela ou estorno de baixa.';
COMMENT ON COLUMN FINANCEIRO.AGENDAMENTO_ID IS 'Preenchido em pagamento à vista, sinal, despesa do evento, devolução ou estorno de à vista/sinal.';
COMMENT ON COLUMN FINANCEIRO.ESPECIE_ID IS 'Espécie real, o que aconteceu de fato (pode diferir da combinada em RECEBER).';

CREATE INDEX IX_FINANCEIRO_DATA_LANCAMENTO ON FINANCEIRO (DATA_LANCAMENTO);

ALTER TABLE FINANCEIRO ADD CONSTRAINT CK_FINANCEIRO_ORIGEM
  CHECK (RECEBER_ID IS NULL OR AGENDAMENTO_ID IS NULL);

COMMIT;

-- ---------------------------------------------------------------------------
-- CLIENTE: CPF -> CPF_CNPJ, endereço detalhado, e-mail, telefone obrigatório
-- ---------------------------------------------------------------------------
DROP INDEX UX_CLIENTE_CPF;

ALTER TABLE CLIENTE ALTER COLUMN CPF TO CPF_CNPJ;
ALTER TABLE CLIENTE ALTER COLUMN ENDERECO TO LOGRADOURO;
ALTER TABLE CLIENTE ALTER COLUMN UF TYPE D_UF;
ALTER TABLE CLIENTE
    ADD EMAIL         VARCHAR(120),
    ADD NUMERO        VARCHAR(10),
    ADD COMPLEMENTO   VARCHAR(60),
    ADD BAIRRO        VARCHAR(80),
    ADD CEP           CHAR(8),
    ADD DATA_CADASTRO DATE DEFAULT CURRENT_DATE NOT NULL;

COMMIT;

-- CPF/CNPJ só com dígitos; o que não tiver 11 ou 14 dígitos é descartado
UPDATE CLIENTE SET CPF_CNPJ = NULLIF(REPLACE(REPLACE(REPLACE(CPF_CNPJ, '.', ''), '-', ''), '/', ''), '');
UPDATE CLIENTE SET CPF_CNPJ = NULL WHERE CHAR_LENGTH(CPF_CNPJ) NOT IN (11, 14);
UPDATE CLIENTE SET TELEFONE = '' WHERE TELEFONE IS NULL;

COMMIT;

ALTER TABLE CLIENTE ALTER COLUMN TELEFONE SET NOT NULL;
ALTER TABLE CLIENTE ALTER COLUMN CPF_CNPJ POSITION 3;
ALTER TABLE CLIENTE ALTER COLUMN TELEFONE POSITION 4;
ALTER TABLE CLIENTE ALTER COLUMN EMAIL POSITION 5;
ALTER TABLE CLIENTE ALTER COLUMN LOGRADOURO POSITION 6;
ALTER TABLE CLIENTE ALTER COLUMN NUMERO POSITION 7;
ALTER TABLE CLIENTE ALTER COLUMN COMPLEMENTO POSITION 8;
ALTER TABLE CLIENTE ALTER COLUMN BAIRRO POSITION 9;

CREATE UNIQUE INDEX UX_CLIENTE_CPF_CNPJ ON CLIENTE (CPF_CNPJ);

ALTER TABLE CLIENTE ADD CONSTRAINT CK_CLIENTE_CPF_CNPJ
  CHECK (CPF_CNPJ IS NULL OR CHAR_LENGTH(CPF_CNPJ) IN (11, 14));

COMMENT ON TABLE CLIENTE IS 'Quem contrata o evento, pessoa física ou jurídica.';
COMMENT ON COLUMN CLIENTE.CPF_CNPJ IS 'Opcional; só dígitos (11 = CPF, 14 = CNPJ); se preenchido, único e válido (RN01).';
COMMENT ON COLUMN CLIENTE.TELEFONE IS 'Obrigatório.';
COMMENT ON COLUMN CLIENTE.EMAIL IS 'Opcional.';
COMMENT ON COLUMN CLIENTE.LOGRADOURO IS 'Endereço opcional: rua/avenida.';
COMMENT ON COLUMN CLIENTE.CEP IS 'Só dígitos (8).';

COMMIT;

-- ---------------------------------------------------------------------------
-- AGENDAMENTO: título, hora de início e fim, observação, data de cadastro
-- ---------------------------------------------------------------------------
ALTER TABLE AGENDAMENTO ALTER COLUMN HORA_EVENTO TO HORA_INICIO;
ALTER TABLE AGENDAMENTO ALTER COLUMN HORA_INICIO SET NOT NULL;
