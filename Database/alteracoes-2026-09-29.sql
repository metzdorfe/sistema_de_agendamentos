    ADD QUANTIDADE_CONVIDADOS SMALLINT,
    ADD OBSERVACAO            VARCHAR(500),
    ADD DATA_CADASTRO         DATE DEFAULT CURRENT_DATE NOT NULL;

COMMIT;

ALTER TABLE AGENDAMENTO ALTER COLUMN TITULO POSITION 3;
ALTER TABLE AGENDAMENTO ALTER COLUMN HORA_FIM POSITION 6;
ALTER TABLE AGENDAMENTO ALTER COLUMN QUANTIDADE_CONVIDADOS POSITION 7;
