ALTER TABLE ADICIONAL_AGENDAMENTO ADD QUANTIDADE SMALLINT DEFAULT 1 NOT NULL;
ALTER TABLE ADICIONAL_AGENDAMENTO ALTER COLUMN QUANTIDADE POSITION 4;
