COMMENT ON COLUMN CONFIGURACAO.TEMA IS 'E=Escuro (padrão), C=Claro, S=Seguir o Windows.';
COMMENT ON COLUMN CONFIGURACAO.NOME_EMPRESA IS 'Usado na navbar, na splash e no catálogo PDF.';
COMMENT ON COLUMN CONFIGURACAO.CNPJ_EMPRESA IS 'Só dígitos.';
COMMENT ON COLUMN CONFIGURACAO.ENDERECO_EMPRESA IS 'Texto livre, uma linha; só é exibido.';
